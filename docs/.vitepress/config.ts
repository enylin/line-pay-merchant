const optional = (value: unknown, check: (value: unknown) => boolean) =>
  value === undefined || check(value)

/** The fields of a sidebar item that TypeDoc writes, checked. */
function isSidebarItem(value: unknown): value is DefaultTheme.SidebarItem {
  if (typeof value !== 'object' || value === null) return false
  return (
    optional(Reflect.get(value, 'text'), text => typeof text === 'string') &&
    optional(Reflect.get(value, 'link'), link => typeof link === 'string') &&
    optional(
      Reflect.get(value, 'collapsed'),
      collapsed => typeof collapsed === 'boolean'
    ) &&
    optional(Reflect.get(value, 'items'), isSidebarItems)
  )
}

function isSidebarItems(value: unknown): value is DefaultTheme.SidebarItem[] {
  return Array.isArray(value) && value.every(isSidebarItem)
}

/** Generated by `npm run docs:api`. Missing on a fresh checkout. */
function apiSidebar(locale: 'root' | 'en'): DefaultTheme.SidebarItem[] {
  const path = locale === 'root' ? '../api' : '../en/api'
  try {
    const sidebar: unknown = JSON.parse(
      readFileSync(
        fileURLToPath(new URL(`${path}/typedoc-sidebar.json`, import.meta.url)),
        'utf8'
      )
    )
    return isSidebarItems(sidebar) ? sidebar : []
  } catch {
    return []
  }
}

